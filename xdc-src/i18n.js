  const LANG_META = [
    { id: 'en', native: 'English' },
    { id: 'es', native: 'Español' }
  ];
  const LANG_IDS = LANG_META.map(function (l) { return l.id; });

  const dict = { es: es, en: en };
  let current = 'es';

  function detect() {
    try {
      const raw = (typeof navigator !== 'undefined' && (navigator.language || (navigator.languages && navigator.languages[0]))) || 'en';
      const nav = String(raw).toLowerCase().replace(/_/g, '-');
      const pre = nav.split('-')[0];
      if (pre === 'es') return 'es';
      return 'en';
    } catch (e) { return 'en'; }
  }

  function resolve(setting) {
    if (setting && dict[setting]) return setting;
    if (setting && LANG_IDS.indexOf(setting) >= 0) return dict[setting] ? setting : 'en';
    return detect();
  }

  function t(key, params) {
    let s = dict[current][key];
    if (s === undefined) s = dict.en[key];
    if (s === undefined) return key; /* la clave se muestra tal cual: detectable en QA */
    if (params) {
      return String(s).replace(/\{(\w+)\}/g, function (m, k) {
        return params[k] !== undefined ? String(params[k]) : m;
      });
    }
    return s;
  }

  function applyDocLang() {
    try {
      if (typeof document !== 'undefined' && document.documentElement) {
        document.documentElement.lang = current || 'es';
      }
    } catch (e) { /* ignore */ }
  }

  const i18n = {
    init: function (setting) { current = resolve(setting); applyDocLang(); return current; },
    setLang: function (setting) { current = resolve(setting); applyDocLang(); return current; },
    lang: function () { return current; },
    t: t,
    detect: detect,
    langs: function () { return LANG_META.slice(); },
    register: function (id, pack) {
      if (!id || !pack) return;
      dict[id] = pack;
      if (current === id) applyDocLang();
    },
    _dict: dict
  };

  CS.i18n = i18n;
  if (typeof module !== 'undefined' && module.exports) { module.exports = i18n; }
